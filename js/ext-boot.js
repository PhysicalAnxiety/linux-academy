  const parseEntries = (cfg) => {
    const lines = cfg.split('\n');
    const top = [];
    let depth = 0;
    let cur = null;
    let sub = null;
    for (const ln of lines) {
      const mm = /^\s*menuentry '([^']+)'/.exec(ln);
      const sm = /^\s*submenu '([^']+)'/.exec(ln);
      if (sm) { sub = { title: sm[1], sub: [] }; top.push(sub); depth = 1; continue; }
      if (mm) { cur = { title: mm[1] }; (sub && depth >= 1 ? sub.sub : top).push(cur); continue; }
      const lm = /^\s*linux\s+(\S+)\s*(.*)$/.exec(ln);
      if (lm && cur) { cur.linux = lm[1]; cur.args = lm[2]; }
      const im = /^\s*initrd\s+(\S+)/.exec(ln);
      if (im && cur) cur.initrd = im[1];
      if (/^}\s*$/.test(ln) && sub && !cur) sub = null;
      if (/^\s*}\s*$/.test(ln) && cur) cur = null;
    }
    return top;
  };
