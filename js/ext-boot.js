  function fstabProblem(sh) {
    for (const e of LX.fstabEntries(sh)) {
      if (e.fs === 'swap' || e.target === '/' || e.target === 'none' || e.target === '/boot/efi' || /nofail/.test(e.opts)) continue;
      if (/^[\w.-]+:\//.test(e.src) || e.fs === 'nfs' || e.fs === 'nfs4' || e.fs === 'tmpfs' || e.fs === 'proc') continue;
      const dev = LX.blockByRef(sh, e.src);
      if (!dev) return { kind: 'device', e };
      if (!sh.fs.lookup(e.target)) return { kind: 'mountpoint', e };
      if (dev.fsBroken) return { kind: 'fs', e };
    }
    return null;
  }
